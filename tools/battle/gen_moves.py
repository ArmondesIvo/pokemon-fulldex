#!/usr/bin/env python3
"""Battle moves table for the PokeHub arena (frontend/battle_moves.h), from PKVault's PokeAPI data.

Usage: gen_moves.py <StaticOthers_en.json.gz> <Showdown data/moves.ts> <out.h>
Each move: its type (0 Normal .. 17 Fairy, PKSM's order), category (0 physical, 1 special,
2 status), power and accuracy (0: never misses), as the latest games have them, its name, and its
SHAPE in the arena, from Showdown's flags and target: 0 a shot, 1 a lunge (it touches: contact),
2 a ring round the user (it hits all round: target allAdjacent), 3 a jet (beams, cannons, pumps,
Flamethrower), 4 a spread of shots (several hits, or all foes round: Razor Leaf, Rock Slide),
5 a wide wave (sound or wind).
"""
import gzip, json, re, sys

src, sd, out = sys.argv[1], sys.argv[2], sys.argv[3]
shape = {}
text = open(sd, encoding="utf-8").read()
for m in re.finditer(r"\n\t(\w+): \{\n(.*?)\n\t\},", text, re.S):
    body = m.group(2)
    num = re.search(r"\n\t\tnum: (-?\d+),", "\n" + body)
    if not num:
        continue
    flags = re.search(r"flags: \{([^}]*)\}", body)
    flags = set(f.split(":")[0].strip() for f in flags.group(1).split(",") if f.strip()) if flags else set()
    target = (re.search(r"target: \"(\w+)\"", body) or [None, ""])[1]
    name = (re.search(r"name: \"([^\"]+)\"", body) or [None, ""])[1]
    multi = "multihit:" in body
    if "contact" in flags: k = 1
    elif target == "allAdjacent": k = 2
    elif re.search(r"Beam|Cannon|Pump|Flamethrower|Water Gun|Blast Burn|Steam Eruption|Origin Pulse|Fire Spin|Whirlpool|Thunderbolt|Thunder Shock|Discharge", name): k = 3
    elif "sound" in flags or "wind" in flags: k = 5
    elif multi or target == "allAdjacentFoes": k = 4
    else: k = 0
    shape[int(num.group(1))] = k
moves = json.load(gzip.open(src))["moves"]
n = max(int(k) for k in moves) + 1
rows = []
for i in range(n):
    m = moves.get(str(i))
    if not m:
        rows.append((0, 2, 0, 0, "", 0))
        continue
    d = m["dataUntilGeneration"][-1]
    t = max(0, d.get("type", 1) - 1)
    if t > 17:
        t = 0
    rows.append((t, d.get("category", 0), d.get("power", 0) or 0, d.get("accuracy", 0) or 0,
                 m.get("name", ""), shape.get(i, 0)))
with open(out, "w", encoding="utf-8") as f:
    f.write("#pragma once\n// Generated by tools/battle/gen_moves.py from PKVault's PokeAPI data: do not edit.\n")
    f.write("namespace BattleData {\nenum { SH_SHOT, SH_LUNGE, SH_RING, SH_JET, SH_SPREAD, SH_WAVE };\nstruct MoveInfo { unsigned char type, cat; unsigned short power; unsigned char acc; const char* name; unsigned char shape; };\n")
    f.write(f"constexpr int MOVE_COUNT = {n};\ninline const MoveInfo& Move(int id)\n{{\n    static const MoveInfo t[] = {{\n")
    for r in rows:
        name = r[4].replace("\\", "\\\\").replace('"', '\\"')
        f.write(f'        {{ {r[0]}, {r[1]}, {r[2]}, {r[3]}, "{name}", {r[5]} }},\n')
    f.write("    };\n    return t[id > 0 && id < MOVE_COUNT ? id : 0];\n}\n}\n")
print(n, "moves")
