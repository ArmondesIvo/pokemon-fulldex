#!/usr/bin/env python3
"""Battle moves table for the PokeHub arena (frontend/battle_moves.h), from PKVault's PokeAPI data.

Usage: gen_moves.py <StaticOthers_en.json.gz> <out.h>
Each move: its type (0 Normal .. 17 Fairy, PKSM's order), category (0 physical, 1 special,
2 status), power and accuracy (0: never misses), as the latest games have them, and its name.
"""
import gzip, json, sys

src, out = sys.argv[1], sys.argv[2]
moves = json.load(gzip.open(src))["moves"]
n = max(int(k) for k in moves) + 1
rows = []
for i in range(n):
    m = moves.get(str(i))
    if not m:
        rows.append((0, 2, 0, 0, ""))
        continue
    d = m["dataUntilGeneration"][-1]
    t = max(0, d.get("type", 1) - 1)
    if t > 17:
        t = 0
    rows.append((t, d.get("category", 0), d.get("power", 0) or 0, d.get("accuracy", 0) or 0,
                 m.get("name", "")))
with open(out, "w", encoding="utf-8") as f:
    f.write("#pragma once\n// Generated by tools/battle/gen_moves.py from PKVault's PokeAPI data: do not edit.\n")
    f.write("namespace BattleData {\nstruct MoveInfo { unsigned char type, cat; unsigned short power; unsigned char acc; const char* name; };\n")
    f.write(f"constexpr int MOVE_COUNT = {n};\ninline const MoveInfo& Move(int id)\n{{\n    static const MoveInfo t[] = {{\n")
    for r in rows:
        name = r[4].replace("\\", "\\\\").replace('"', '\\"')
        f.write(f'        {{ {r[0]}, {r[1]}, {r[2]}, {r[3]}, "{name}" }},\n')
    f.write("    };\n    return t[id > 0 && id < MOVE_COUNT ? id : 0];\n}\n}\n")
print(n, "moves")
